def should_skip_text(txt):
    s = txt.strip()
    if len(s) <= 1 or not re.search(r"[A-Za-zÄÖÜäöüß]", s):
        return True
    if re.match(r"^(S\.|p\.)\s*[\d,\s]+$", s):
        return True
    return False

def merge_runs(p_el):
    for pe in list(p_el.findall("w:proofErr", NS)):
        p_el.remove(pe)
    def run_sig(r_el):
        if r_el.tag.split("}")[-1] != "r":
            return None
        for tag in ("w:drawing", "w:fldChar", "w:instrText", "w:tab", "w:br"):
            if r_el.find(tag, NS) is not None:
                return None
        rPr = r_el.find("w:rPr", NS)
        b = rPr is not None and rPr.find("w:b", NS) is not None
        it = rPr is not None and rPr.find("w:i", NS) is not None
        col = rPr.find("w:color", NS).attrib.get(qn("w:val"), "") if (rPr is not None and rPr.find("w:color", NS) is not None) else ""
        return (b, it, col)
    prev_r, prev_sig = None, None
    for ch in list(p_el):
        sig = run_sig(ch)
        if sig is not None and prev_r is not None and sig == prev_sig:
            t_cur = "".join(t.text or "" for t in ch.findall("w:t", NS))
            t_prev = prev_r.findall("w:t", NS)
            if t_prev:
                t_prev[0].set(qn("w:space"), "preserve")
                t_prev[0].text = (t_prev[0].text or "") + t_cur
                for extra in t_prev[1:]:
                    prev_r.remove(extra)
                p_el.remove(ch)
                continue
        prev_r = ch if sig is not None else None
        prev_sig = sig

MONTHS = [("Januar","1月"),("Februar","2月"),("März","3月"),("April","4月"),
 ("Juni","6月"),("Juli","7月"),("August","8月"),("September","9月"),
 ("Oktober","10月"),("November","11月"),("Dezember","12月")]
# NOTE: Mai (5月) absichtlich ausgespart (Substring-Risiko in ,,Main/Domain'').

def _guarded_replace(work, de, ja):
    """Substring-Guard: blosse Einzeltoken (keine Leer-/Sonderzeichen) nur an
    Wortgrenzen ersetzen, damit Locks (URLs, Pfade, Produktnamen, IDs) und
    laengere Woerter nicht teilersetzt werden. Phrasen mit Delimitern wie
    bisher per plain replace (schnell + exakt)."""
    if not de:
        return work
    if " " in de or not re.fullmatch(r"[A-Za-z\u00c4\u00d6\u00dc\u00e4\u00f6\u00fc\u00df]+", de):
        if de in work:
            return work.replace(de, ja)
        return work
    if de not in work:
        return work
    return re.sub(r"(?<!\w)%s(?!\w)" % re.escape(de), ja, work)

def offline_translate(txt):
    """Eigenes Wissen: DE->JA per kuratierter Terminologie, Locks bewahrt."""
    if should_skip_text(txt):
        return txt
    # 1) Volle Phrasen ZUERST (enthalten teils Lock-Tokens wie MCP/RAG/Obsidian)
    work = txt
    # Pre-Reparatur: volle DE-Phrasen VOR Einzelwort-Ersetzung (danach
    # sind sie durch Teilersetzungen nicht mehr exakt auffindbar)
    for de, ja in REPAIRS:
        work = _guarded_replace(work, de, ja)
    for de, ja in sorted(PHRASES, key=lambda x: -len(x[0])):
        work = _guarded_replace(work, de, ja)
    for de, ja in MONTHS:
        work = re.sub(r"\b%s\b" % de, ja, work)
    # Reparatur: Lock-Phrasen, die durch Einzelwort-Ersetzung getroffen wurden
    # (muss NACH dem PHRASES-Loop laufen, da der Schaden dort entsteht)
    for de, ja in REPAIRS:
        work = _guarded_replace(work, de, ja)
    work = re.sub(r"\bMai\b(?!\w)", "5月", work)
    # 2) Locks stashen, dann Wort-Ebene
    locks = []
    def stash(m):
        locks.append(m.group(0))
        return "\x00%d\x00" % (len(locks) - 1)
    work = LOCK_RX.sub(stash, work)
    # Abb. X: -> 図 X:
    work = re.sub(r"\bAbb\.(\s*\d+)", r"図\1", work)
    work = re.sub(r"\bAbb\.", "図", work)
    for de, ja in WORDS:
        work = _guarded_replace(work, de, ja)
    # Sprache/Stand-Zeile
    work = work.replace("Deutsch", "日本語")
    work = work.replace("(DE)", "(JA)")
    # Platzhalter zurück
    for i, tok in enumerate(locks):
        work = work.replace("\x00%d\x00" % i, tok)
    work = EMOJI_RX.sub("", work)
    # Leerzeichen vor JA-Partikeln normalisieren
    work = re.sub(r"\s+([、。：；（）「」])", r"\1", work)
    work = re.sub(r"[ ]{2,}", " ", work)
    return work

def collect_targets(doc):
    body = doc._body._body
    toc_ps = {p_el for sdt in body.findall("w:sdt", NS) for p_el in sdt.findall(".//w:p", NS)}
    targets, uniq, seen = [], [], set()
    for p_el in body.iter():
        if p_el.tag.endswith("}p") and p_el not in toc_ps:
            merge_runs(p_el)
            for r_el in p_el.findall("w:r", NS):
                if r_el.find("w:drawing", NS) is not None or r_el.find("w:fldChar", NS) is not None:
                    continue
                t_els = r_el.findall("w:t", NS)
                if not t_els:
                    continue
                t = "".join(x.text or "" for x in t_els)
                if should_skip_text(t):
                    continue
                targets.append((r_el, t_els, t))
                if t not in seen:
                    seen.add(t)
                    uniq.append(t)
    return body, targets, uniq

def process_one(src, dst):
    doc = docx.Document(src)
    body, targets, uniq = collect_targets(doc)
    cache = {}
    if os.path.exists(CACHE):
        with open(CACHE, "r", encoding="utf-8") as f:
            cache = json.load(f)
    pending = [u for u in uniq if u not in cache]
    print(f"{src}: Segmente gesamt {len(targets)} | Unique {len(uniq)} | Pending {len(pending)}", flush=True)
    os.makedirs(os.path.dirname(CACHE) or ".", exist_ok=True)
    for i in range(0, len(pending), BATCH):
        batch = pending[i:i+BATCH]
        for s in batch:
            cache[s] = offline_translate(s)
        with open(CACHE, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False, indent=1)
        print(f"  batch {(i//BATCH)+1}: {min(i+BATCH, len(pending))}/{len(pending)}", flush=True)
    for r_el, t_els, t in targets:
        tr = cache.get(t, t)
        if t.startswith(" ") and not tr.startswith(" "):
            tr = " " + tr
        if t.endswith(" ") and not tr.endswith(" "):
            tr = tr + " "
        t_els[0].set(qn("w:space"), "preserve")
        t_els[0].text = tr
        for extra in t_els[1:]:
            r_el.remove(extra)
    for sdt in body.findall("w:sdt", NS):
        for t in sdt.findall(".//w:t", NS):
            if t.text and t.text.strip() in ("Inhalt", "Table of Contents"):
                t.text = "目次"
    for el in body.iter():
        if el.tag.endswith("}lang"):
            el.set(qn("w:val"), "ja-JP")
        elif el.tag.endswith("}t") and el.text and "(DE)" in el.text:
            el.text = el.text.replace("(DE)", "(JA)")
    if doc.tables:
        last_tbl = doc.tables[-1]
        trs = last_tbl._tbl.findall("w:tr", NS)
        if len(trs) > 2:
            data_trs = trs[1:]
            srt = sorted(data_trs, key=lambda tr: "".join(x.text or "" for x in tr.findall("w:tc", NS)[0].findall(".//w:t", NS)).strip().lower())
            for r in data_trs:
                last_tbl._tbl.remove(r)
            for idx, r in enumerate(srt):
                for tc in r.findall("w:tc", NS):
                    tcPr = tc.find("w:tcPr", NS)
                    if tcPr is not None:
                        old = tcPr.find("w:shd", NS)
                        if old is not None:
                            tcPr.remove(old)
                        if idx % 2 == 1:
                            shd = OxmlElement("w:shd")
                            shd.set(qn("w:val"), "clear")
                            shd.set(qn("w:color"), "auto")
                            shd.set(qn("w:fill"), "F8FAFC")
                            tcPr.append(shd)
                last_tbl._tbl.append(r)
    doc.save(dst)
    print(f"Gespeichert: {dst}", flush=True)
    return len(targets)

