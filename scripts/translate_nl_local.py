def protect(text):
    # Zuerst URLs/Pfade/Code stachen (rohe URLs enthalten ggf. LOCKED-Terme wie n8n),
    # danach erst LOCKED-Terme schützen, damit keine Marker in gestachten URLs landen.
    m: list[str] = []
    def stash(pat, txt):
        def rep(mo):
            k=f"\u0001{len(m)}\u0001"
            m.append(mo.group(0))
            return k
        return re.sub(pat, rep, txt)
    text=stash(r"https?://\S+|www\.\S+|[\w\-./]*\.(?:docx|pdf|xlsx|enc|json|ya?ml|md|db|exe|ps1)|`[^`]+`|\bv\d+\.\d+\.\d+|\b\d{2,5}\b(?=\s*(?:port|Port))", text)
    slots={}
    for i,t in enumerate(sorted(LOCKED,key=len,reverse=True)):
        if t in text:
            k=f"\u0000{i}\u0000"
            slots[k]=t
            text=text.replace(t,k)
    return text, slots, m

def restore(text, slots, m):
    for k,v in slots.items():
        text=text.replace(k,v)
    for i,v in enumerate(m):
        text=text.replace(f"\u0001{i}\u0001", v)
    return text

def apply_case(src, dst):
    if not dst: return dst
    if src and src[0].isupper():
        return dst[0].upper()+dst[1:]
    return dst

def local_translate(text):
    if not text or not text.strip(): return text
    lead=len(text)-len(text.lstrip())
    trail=len(text)-len(text.rstrip())
    core=text.strip()
    p_core, slots, m = protect(core)
    # Abb. -> Fig.
    p_core=re.sub(r"\bAbb\.", "Fig.", p_core)
    # phrases longest first
    # phrases longest first (case-insensitive, keep first-letter case)
    for de,nl in sorted(PHRASES,key=lambda x:len(x[0]),reverse=True):
        pat=re.compile(re.escape(de), re.IGNORECASE)
        def _r(mo, nl=nl):
            s=mo.group(0)
            return apply_case(s,nl)
        p_core=pat.sub(_r, p_core)
    PRO = [("Sie","u"),("Ihnen","u"),("Ihrem","uw"),("Ihren","uw"),("Ihrer","uw"),("Ihre","uw"),("Ihres","uw"),("Ihr","uw"),("Ihm","u"),("Ihn","u")]
    # polite forms, case-sensitive, before single-word pass
    for de,nl in PRO:
        pat=re.compile(r"(?<![\wÄÖÜäöüß])"+re.escape(de)+r"(?![\wÄÖÜäöüß])")
        p_core=pat.sub(nl, p_core)
    # words: case-insensitive whole word
    for de,nl in sorted(WORDS.items(),key=lambda x:len(x[0]),reverse=True):
        pat=re.compile(r"(?<![\wÄÖÜäöüß])"+re.escape(de)+r"(?![\wÄÖÜäöüß])", re.IGNORECASE)
        def _w(mo, nl=nl):
            s=mo.group(0)
            if s.isupper() and len(s)>1:
                return nl.upper()
            return apply_case(s,nl)
        p_core=pat.sub(_w, p_core)
    out=restore(p_core, slots, m)
    prefix=text[:lead] if lead else ""
    suffix=text[len(text)-trail:] if trail else ""
    return prefix+out+suffix

